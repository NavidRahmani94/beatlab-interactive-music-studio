const { chromium } = require('playwright');
const URL = process.argv[2]; const results = [];
const ok = (n, c, d = '') => { results.push(c); console.log((c ? 'PASS ' : 'FAIL ') + n + (d ? '  [' + d + ']' : '')); };
(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 1280, height: 1000 } })).newPage(); const errs = [];
  p.on('pageerror', e => errs.push(String(e))); p.on('dialog', d => d.accept());
  await p.goto(URL); await p.waitForTimeout(1000);
  await p.click('button[role="tab"]:text-is("SYNTH")');
  const sec = 'section[aria-label="Synth track"]';
  const cells = () => p.$$eval(`${sec} button[aria-pressed="true"][data-step]`, e => e.length);
  ok('chord builder starts closed', !(await p.isVisible('[aria-label="Chord builder"]')));
  await p.click('text=CHORD BUILDER');
  ok('seven chord buttons', (await p.$$('button[aria-label^="Insert chord"]')).length === 7);
  const c0 = await cells();
  await p.click('button[aria-label^="Insert chord"] >> nth=0');
  const c1 = await cells(); ok('a triad adds 3 notes (4 steps each)', c1 === c0 + 12, `${c0}->${c1}`);
  ok('position moved forward by the length', (await p.inputValue('select[aria-label="Chord position"]')) === '4');
  await p.click('input[type="checkbox"]'); await p.click('button[aria-label^="Insert chord"] >> nth=3');
  const c2 = await cells(); ok('a 7th chord adds 4 notes (4 steps each)', c2 === c1 + 16, `${c1}->${c2}`);
  ok('suggestions are shown', (await p.$$('.chip-note')).length >= 2);
  await p.click('button[aria-label="Undo"]'); await p.waitForTimeout(100);
  await p.waitForTimeout(700); 
  await p.selectOption('select[aria-label="Progression"]', { index: 1 });
  await p.click('text=USE PROGRESSION');
  const c3 = await cells(); ok('a progression fills the pattern (4 chords)', c3 >= 12, `${c3}`);
  ok('last chord starts at step 25', await p.isVisible(`${sec} button[data-step="24"][aria-pressed="true"]`) || (await p.$$(`${sec} button[data-step="24"][aria-pressed="true"]`)).length > 0);
  await p.click('button[role="tab"]:text-is("DRUMS")'); await p.click('button[role="tab"]:text-is("MELODY")');
  ok('builder available on every note track', await p.isVisible('text=CHORD BUILDER'));
  ok('no page errors', errs.length === 0, errs.join('|'));
  await p.screenshot({ path: 'e2e-out/chords.png' });
  await b.close();
  console.log(results.every(Boolean) ? 'ALL PASS' : 'SOME FAILED', results.filter(Boolean).length + '/' + results.length);
})();
